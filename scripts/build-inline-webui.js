const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_HTML = path.join(ROOT, 'web-ui', 'inscription.html');
const DEFAULT_WEIGHTS = path.join(ROOT, 'pleb.slop');
const DEFAULT_OUT = path.join(ROOT, 'web-ui', 'inscription.inline.html');

const htmlPath = path.resolve(ROOT, process.argv[2] || DEFAULT_HTML);
const weightsPath = path.resolve(ROOT, process.argv[3] || DEFAULT_WEIGHTS);
const outPath = path.resolve(ROOT, process.argv[4] || DEFAULT_OUT);

const html = fs.readFileSync(htmlPath, 'utf8');
const weights = fs.readFileSync(weightsPath);
const base64 = weights.toString('base64');

function replaceBootstrap(source) {
  const marker = '    // Bootstrap from blockchain, falling back to local file if not under ord';
  const start = source.indexOf(marker);
  if (start === -1) {
    throw new Error('Could not find bootstrap marker in inscription HTML');
  }

  const fnStart = source.indexOf('    async function bootstrapModel() {', start);
  if (fnStart === -1) {
    throw new Error('Could not find bootstrapModel function');
  }

  const initStart = source.indexOf('    async function init() {', fnStart);
  if (initStart === -1) {
    throw new Error('Could not find init function after bootstrapModel');
  }

  const replacement = `    // Embedded single-file model artifact. Generated by scripts/build-inline-webui.js.
    const EMBEDDED_SLOP_BASE64 = '${base64}';

    function embeddedSlopBytes() {
        const binary = atob(EMBEDDED_SLOP_BASE64);
        const bytes = new Uint8Array(binary.length);
        for (let i = 0; i < binary.length; i++) {
            bytes[i] = binary.charCodeAt(i);
        }
        return bytes.buffer;
    }

    // Bootstrap from the embedded model bytes. This build does not fetch child inscriptions.
    async function bootstrapModel() {
        const tensors = await SlopParser.parse(embeddedSlopBytes());
        model._loadTensors(tensors);
        model.loaded = true;
    }

`;

  return source.slice(0, start) + replacement + source.slice(initStart);
}

function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([{}:;,>+~])\s*/g, '$1')
    .replace(/;}/g, '}')
    .trim();
}

function minifyJs(js) {
  return js
    .replace(/^\s*\/\/.*$/gm, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map(line => line.trim())
    .filter(Boolean)
    .join('\n')
    .replace(/\n+/g, '\n')
    .trim();
}

function minifyHtml(source) {
  const parts = [];
  let cursor = 0;
  const blockRe = /<(style|script)(\b[^>]*)>([\s\S]*?)<\/\1>/gi;
  let match;

  while ((match = blockRe.exec(source))) {
    const before = source.slice(cursor, match.index);
    parts.push(
      before
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/\s+/g, ' ')
        .replace(/>\s+</g, '><')
        .trim()
    );

    const tag = match[1].toLowerCase();
    const attrs = match[2] || '';
    const body = tag === 'style' ? minifyCss(match[3]) : minifyJs(match[3]);
    parts.push(`<${tag}${attrs}>${body}</${tag}>`);
    cursor = blockRe.lastIndex;
  }

  parts.push(
    source
      .slice(cursor)
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\s+/g, ' ')
      .replace(/>\s+</g, '><')
      .trim()
  );

  return parts.filter(Boolean).join('').replace(/>\s+</g, '><').trim() + '\n';
}

const inlined = replaceBootstrap(html);
const minified = minifyHtml(inlined);
fs.writeFileSync(outPath, minified);

const gzipSize = zlib.gzipSync(minified, { level: 9 }).length;

console.log(`html:     ${path.relative(ROOT, htmlPath)} (${html.length.toLocaleString()} bytes)`);
console.log(`weights:  ${path.relative(ROOT, weightsPath)} (${weights.length.toLocaleString()} bytes)`);
console.log(`output:   ${path.relative(ROOT, outPath)} (${Buffer.byteLength(minified).toLocaleString()} bytes)`);
console.log(`gzip -9:  ${gzipSize.toLocaleString()} bytes`);
console.log(`base64:   ${base64.length.toLocaleString()} bytes`);
